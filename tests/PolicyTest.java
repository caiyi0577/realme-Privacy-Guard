import com.caiyi.rpg.DomainPolicy;
import com.caiyi.rpg.Prefs;
import com.caiyi.rpg.TargetCatalog;
import com.caiyi.rpg.ProcessIdentity;
import com.caiyi.rpg.LogLedger;
import com.caiyi.rpg.ConfigAccess;
import com.caiyi.rpg.BlockStatus;

public final class PolicyTest {
    private static int checks;
    private static void check(boolean condition,String message) {
        checks++;if(!condition)throw new AssertionError(message);
    }
    public static void main(String[] args) {
        Prefs p=new Prefs();
        check(DomainPolicy.hostMatches("DM.WO.COM.CN.","dm.wo.com.cn"),"case/trailing dot");
        check(DomainPolicy.hostMatches("sub.dm.wo.com.cn","dm.wo.com.cn"),"subdomain");
        check(!DomainPolicy.hostMatches("dm.wo.com.cn.attacker.test","dm.wo.com.cn"),"suffix boundary");
        check(!DomainPolicy.hostMatches("notdm.wo.com.cn","dm.wo.com.cn"),"label boundary");
        check(!DomainPolicy.blockedHost(TargetCatalog.UMS,"breeno.apps.coloros.com",p),"do not block multipurpose UMS host in DNS");
        check(DomainPolicy.blockedUrl(TargetCatalog.UMS,"https://breeno.apps.coloros.com/sms-model/v1/upload?x=1",p),"SMS upload path");
        check(!DomainPolicy.blockedUrl(TargetCatalog.UMS,"https://breeno.apps.coloros.com/proxy/app-download/v1/get-app-detail",p),"retain unrelated UMS API");
        check(!DomainPolicy.blockedUrl(TargetCatalog.UMS,"https://breeno.apps.coloros.com.attacker.test/sms-model/v1/upload",p),"host boundary in URL");
        check(DomainPolicy.blockedHost("com.coloros.regservice","a.fxltsbl.com",p),"RegService production");
        check(!DomainPolicy.blockedHost("com.coloros.weather.service","a.fxltsbl.com",p),"RegService scope isolation");
        p.ums=false;check(!DomainPolicy.blockedUrl(TargetCatalog.UMS,"https://nearby.dc.oppomobile.com/api/v2/report_position",p),"UMS switch off");
        check(DomainPolicy.blockedUrl(TargetCatalog.OLC,"https://dynamic.example/eap/logupload/business/v1",p),"OLC audited path");
        check(!DomainPolicy.blockedUrl("com.coloros.weather.service","https://dynamic.example/eap/logupload/business/v1",p),"OLC scope isolation");
        StringBuilder stat=new StringBuilder("123 (a process (name)) S");
        for(int field=4;field<=52;field++)stat.append(' ').append(field==22?"99123":"0");
        check(ProcessIdentity.startTicks(stat.toString()).equals("99123"),"proc name with parentheses/spaces");
        check(!ProcessIdentity.matches("123","99123","123","99124"),"reused PID rejected");
        check(!ProcessIdentity.matches("123","unknown","123","unknown"),"unknown start cannot validate");
        LogLedger ledger=new LogLedger();String pkg=TargetCatalog.UMS;
        String prefix="[RPG2]|"+TargetCatalog.HOOK_VERSION+"|123|99123|"+pkg+"|"+pkg+"|";
        ledger.accept(prefix+"LOAD|module|active",pkg,"123","99123");
        ledger.accept(prefix+"OK|ums-sms-upload|exactSignature",pkg,"123","99123");
        ledger.accept(prefix+"OK|ums-sms-upload|exactSignature",pkg,"123","99123");
        ledger.accept(prefix+"HIT|ums-sms-upload|64",pkg,"123","99123");
        ledger.accept(prefix+"HIT|ums-sms-upload|1",pkg,"123","99123");
        LogLedger.Entry e=ledger.get(pkg,"123","99123");
        check(e!=null&&e.loaded&&e.ok.size()==1&&e.observedHits()==64,"deduplicate logs and monotone counters");
        ledger.accept(prefix+"FAIL|missing|NoSuchMethod",pkg,"123","99124");
        check(ledger.get(pkg,"123","99124")==null,"old process log cannot prove current load");
        LogLedger other=new LogLedger();other.accept(prefix.replace(TargetCatalog.HOOK_VERSION,"1.0")+"LOAD|module|active",pkg,"123","99123");
        check(other.get(pkg,"123","99123")==null,"old module version rejected");
        check(TargetCatalog.PACKAGES.length==17&&TargetCatalog.isNarrow(TargetCatalog.UMS),"catalog contains new narrow rules");
        check(ConfigAccess.allowed(10040,10040,null),"own UID can read settings");
        check(ConfigAccess.allowed(10154,10040,new String[]{TargetCatalog.UMS}),"audited target can read settings");
        check(ConfigAccess.allowed(1000,10040,new String[]{"android",TargetCatalog.OLC}),"shared UID containing a target can read booleans");
        check(!ConfigAccess.allowed(2000,10040,new String[]{"com.android.shell"}),"shell cannot read settings");
        check(!ConfigAccess.allowed(12345,10040,new String[]{TargetCatalog.UMS+".other"}),"package prefix cannot impersonate target");
        check(!ConfigAccess.allowed(12345,10040,null),"unresolved caller is rejected");
        BlockStatus.Evidence status=new BlockStatus.Evidence();
        status.installed=true;status.moduleEnabled=true;status.scoped=true;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.NOT_RUNNING&&BlockStatus.evaluate(status).line().startsWith("状态：未运行（"),"stopped process has a separate not-running state");
        status.disabled=true;
        check(BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("已禁用"),"disabled component is blocked by OS state");
        status.disabled=false;status.running=1;
        check(!BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("待重启"),"missing current logs cannot prove a block");
        status.loaded=1;status.hooks=6;status.ready=1;
        check(BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("规则已就绪"),"ready blocking hooks count as protection before an upload is attempted");
        status.hits=1;
        check(BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).line().startsWith("状态：阻断（"),"verified hit produces blocked label");
        status.running=2;
        check(BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("1 个进程待验证"),"mixed processes retain a visible coverage limitation");
        status.hits=0;status.ready=0;
        check(!BlockStatus.evaluate(status).blocked,"partial load without hits stays unverified");
        status.running=1;status.configRead=false;
        check(!BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("配置读取未确认"),"failed config does not produce a positive status");
        status.configRead=true;status.failed=1;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.FAILED&&BlockStatus.evaluate(status).reason.contains("失败"),"failed rules have a separate failure status");
        status.failed=0;status.scoped=false;
        check(!BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("未勾选"),"missing scope is explained");
        status.scoped=true;status.moduleEnabled=false;
        check(!BlockStatus.evaluate(status).blocked&&BlockStatus.evaluate(status).reason.contains("未启用"),"disabled module is explained");
        status.running=0;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.NOT_RUNNING,"not running stays distinct when module is off");
        status.hits=64;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.NOT_RUNNING,"past evidence cannot make a non-running process look active");
        status.installed=false;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.UNBLOCKED,"unknown installation is not presented as verified not-running");
        status.installed=true;status.disabled=true;
        check(BlockStatus.evaluate(status).state==BlockStatus.State.BLOCKED,"disabled component retains blocked status rather than not-running");
        BlockStatus.Evidence ready=new BlockStatus.Evidence();ready.installed=true;ready.moduleEnabled=true;ready.scoped=true;
        ready.running=2;ready.loaded=2;ready.ready=1;ready.hooks=6;
        check(BlockStatus.evaluate(ready).blocked&&BlockStatus.evaluate(ready).reason.contains("1 个进程待验证"),"partial readiness is reported explicitly");
        ready.running=1;ready.skipped=1;
        check(BlockStatus.evaluate(ready).blocked,"optional unavailable interfaces do not hide ready protection");
        ready.configRead=false;
        check(BlockStatus.evaluate(ready).blocked&&BlockStatus.evaluate(ready).reason.contains("默认配置"),"installed blocking hooks remain active with an explicit defaults warning");
        ready.configRead=true;
        ready.ready=0;ready.missingRequired=1;
        check(BlockStatus.evaluate(ready).state==BlockStatus.State.FAILED&&BlockStatus.evaluate(ready).reason.contains("关键"),"missing required hooks have an explicit failure state");
        LogLedger rotated=new LogLedger();rotated.accept(prefix+"OK|ums-sms-upload|signature",pkg,"123","99123");
        rotated.accept(prefix+"DONE|configuration|ok",pkg,"123","99123");
        check(rotated.get(pkg,"123","99123").loaded&&rotated.get(pkg,"123","99123").done,"current initialization remains valid without the rotated LOAD row");
        ready.missingRequired=0;ready.failed=1;ready.ready=1;ready.hits=4;
        check(BlockStatus.evaluate(ready).state==BlockStatus.State.FAILED&&BlockStatus.evaluate(ready).reason.contains("4 次"),"working hooks do not conceal a partial blocking failure");
        ready.running=0;
        check(BlockStatus.evaluate(ready).state==BlockStatus.State.NOT_RUNNING,"non-running status does not reuse failures from an inactive process");
        ready.disabled=true;
        check(BlockStatus.evaluate(ready).state==BlockStatus.State.BLOCKED,"disabled component remains blocked independently of hook failure evidence");
        LogLedger failedLog=new LogLedger();failedLog.accept(prefix+"FAIL|initialization|NoSuchMethodError",pkg,"123","99123");
        check(failedLog.get(pkg,"123","99123").loaded&&failedLog.get(pkg,"123","99123").failed.size()==1,"failure-only records survive rotation of the LOAD row");
        System.out.println("PASS: "+checks+" privacy policy and diagnostic edge cases");
    }
}
